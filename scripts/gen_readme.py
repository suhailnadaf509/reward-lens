ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"

#: Rich reads this to decide where to wrap. Pinned so a narrow terminal on somebody's laptop does
#: not rewrite the front page.
CAPTURE_COLUMNS = "92"

_MARKER_RE = re.compile(
    r"(?P<open><!-- generated: (?P<name>[a-z0-9-]+) -->\n)(?P<body>.*?)"
    r"(?P<close><!-- /generated: (?P=name) -->)",
    re.S,
)


class SourceDrift(RuntimeError):
    """An extractor could not find what it was told to find.

    Raised rather than warned, and raised with the file and the pattern in the message, because the
    failure mode this whole script exists to prevent is a page that keeps saying a number after the
    thing that measured it has moved.
    """


class MissingArtifact(RuntimeError):
    """A block's source artifact is not in this checkout, so the block cannot be regenerated.

    Not a failure. `SourceDrift` is for an artifact that is present and no longer says what the page
    quotes, which is a bug. This is for an artifact that was never here: a run output published
    elsewhere, or a directory a release tree does not carry. The block is skipped and whatever the
    README already says is left alone.
    """


class ReadmeDrift(RuntimeError):
    """``--check`` found a block on disk that does not match what regenerating produces."""


# ---------------------------------------------------------------------------
# Running things
# ---------------------------------------------------------------------------


def _env() -> dict[str, str]:
    env = dict(os.environ)
    env["COLUMNS"] = CAPTURE_COLUMNS
    env["PYTHONHASHSEED"] = "0"
    env["NO_COLOR"] = "1"
    env["TERM"] = "dumb"
    return env


def capture(argv: list[str], *, cwd: Path = ROOT, timeout: int = 600) -> str:
    """Run a command and return its stdout, or raise with enough to debug it.

    stderr is deliberately not merged in. A warning from a dependency is not part of the example,
    and merging the two streams would make the page churn every time somebody's numpy changes its
    deprecation schedule.
    """
    proc = subprocess.run(
        argv, cwd=cwd, env=_env(), capture_output=True, text=True, timeout=timeout
    )
    if proc.returncode != 0:
        raise SourceDrift(
            f"{' '.join(argv)} exited {proc.returncode}. The README shows this command's output, "
            f"so a command that fails here is a README that would be lying.\n"
            f"--- stderr ---\n{proc.stderr.strip()[-2000:]}"
        )
    return proc.stdout


def console_script(name: str) -> str:
    """Resolve a console script next to the interpreter running this file.

    Not ``shutil.which`` against a bare PATH. A generator that captures whichever ``reward-lens``
    happens to be first on somebody's PATH can render a README from a different installation than
    the one in the checkout, which is a page describing code that is not the code.
    """
    candidate = Path(sys.executable).parent / name
    if candidate.is_file():
        return str(candidate)
    found = shutil.which(name)
    if found is None:
        raise SourceDrift(
            f"no {name!r} console script beside {sys.executable}. Install the package into the "
            f"environment you are running this from: `pip install -e '.[verifier]'`."
        )
    return found


def read(path: Path) -> str:
    if not path.is_file():
        raise SourceDrift(
            f"{path.relative_to(ROOT)} does not exist, and the README quotes it. Either the "
            f"artifact moved and this script needs repointing, or it was never rendered."
        )
    return path.read_text(encoding="utf-8")


def extract(path: Path, pattern: str, *, what: str, group: int = 1) -> str:
    """Pull one value out of a source file, failing loudly if the pattern no longer matches."""
    m = re.search(pattern, read(path))
    if m is None:
        raise SourceDrift(
            f"could not find {what} in {path.relative_to(ROOT)} using /{pattern}/. The README "
            f"carries this number, so it has to come from here or not be on the page."
        )
    return m.group(group)


def rewrap(text: str, width: int = int(CAPTURE_COLUMNS)) -> str:
    """Hard-wrap over-long lines at the same column Rich wraps at, keeping each line's indent.

    The rendered grader cards were written to disk with no width limit, because a card is read in
    an editor and a remedy string broken across lines is harder to copy. On a README the same line
    scrolls off the side, so it is wrapped here rather than shortened: every word survives, and the
    only thing that changes is where the line ends. Nothing else on the page is re-flowed.
    """
    out: list[str] = []
    for line in text.splitlines():
        if len(line) <= width:
            out.append(line)
            continue
        indent = " " * (len(line) - len(line.lstrip()))
        out.extend(
            textwrap.wrap(
                line.strip(),
                width=width,
                initial_indent=indent,
                subsequent_indent=indent + "  ",
                break_long_words=False,
                break_on_hyphens=False,
            )
        )
    return "\n".join(out)


def fence(text: str, lang: str = "text") -> str:
    """Wrap captured output in a code fence.

    Not decoration. `artifacts/claims.py` masks fenced blocks before it looks for unbound numbers,
    and that is the right rule rather than a loophole: a number inside a fence is output rather
    than an assertion, and the fence is the page saying so. It is also why this script puts every
    measured decimal inside one, so README.md passes the claims gate with no baseline of its own.
    """
    return f"```{lang}\n{text.rstrip()}\n```"


# ---------------------------------------------------------------------------
# The registry
# ---------------------------------------------------------------------------


@dataclass
class Registry:
    """One snapshot of what the library knows about itself."""

    n_instruments: int
    n_wedge_instruments: int
    n_quantities: int
    n_wedge_quantities: int
    n_series: int
    reasons: tuple[tuple[str, str], ...]
    n_invariance_groups: int
    n_regime_conditions: int


def load_registry() -> Registry:
    """Read the live registry, the way `docs/gen_catalogue.py` does.

    Deliberately the loader the capability report itself uses, rather than the YAML, so a count on
    the front page and a count in the capability report cannot disagree.
    """
    from reward_lens.access.report import load_instrument_catalogue
    from reward_lens.core.envelope import RegimeCondition
    from reward_lens.core.invariance import GROUPS
    from reward_lens.core.quantity import QUANTITIES, load_quantities
    from reward_lens.core.reading import REASON_MEANING, RefusalReason

    load_quantities()
    instruments = load_instrument_catalogue()
    reasons = tuple(
        (r.name, " ".join(REASON_MEANING[r].split()))
        for r in sorted(RefusalReason, key=lambda x: x.name)
    )
    return Registry(
        n_instruments=len(instruments),
        n_wedge_instruments=sum(1 for i in instruments if i.wedge),
        n_quantities=len(QUANTITIES),
        n_wedge_quantities=sum(1 for q in QUANTITIES.values() if q.wedge),
        n_series=len({i.id[0] for i in instruments if i.id}),
        reasons=reasons,
        # `trivial` is not one of them. It is the declaration a quantity makes when it has no
        # non-trivial invariance to respect, and counting it would inflate the number. It has
        # exactly one spelling so that the count cannot depend on which one a caller used.
        n_invariance_groups=len([g for g in GROUPS if g != "trivial"]),
        n_regime_conditions=len(RegimeCondition),
    )


