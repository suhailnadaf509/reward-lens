"""Render every example and every number in README.md from code that ran.

The front page is the most-read prose in the project and it is the page where a number that came
from somewhere other than a run does the most damage. So the rule for README.md is stricter than
the rule for the rest of the documentation: an example is generated by this script, or it is not on
the page. Nothing is transcribed, nothing is "checked", nothing is true-as-of-when-it-was-written.

Three kinds of block, and the difference matters:

- **Captured.** A subprocess runs a shipped entry point and its stdout goes on the page verbatim.
  ``reward-lens capabilities`` and the card-plan example are both this. What the page shows is what
  the reader gets, including when that is disappointing.
- **Read from the registry.** The instrument and quantity counts, and the seventeen refusal
  reasons, come from ``reward_lens.core`` at generation time, the same source
  ``docs/gen_catalogue.py`` uses. A count on the page cannot disagree with the catalogue.
- **Extracted.** A measured number is lifted out of the artifact that produced it, by a pattern
  anchored on the surrounding sentence, and a pattern that no longer matches is a hard failure
  rather than a stale line. The extractors are the interesting part of this file: each one names
  the file it reads and what it expects to find there, so a number that moves in the tree takes the
  README with it instead of leaving it behind.

Markers in README.md delimit each block::

    <!-- generated: capabilities -->
    ...
    <!-- /generated: capabilities -->

Everything between them is owned by this script. Everything outside is prose a person wrote.

**Optional blocks.** Some blocks are extracted from large run artifacts that are published
separately rather than carried in the source tree. When such an artifact is not in the checkout the
block is *skipped*: the text already in README.md is left exactly as it stands, the reason is
printed, and ``--check`` still passes. That is deliberately different from drift. Drift means the
source is here and no longer says what the page quotes, which is a bug and fails the build. A
missing artifact means the page cannot be regenerated from this checkout at all, and rewriting it to
say less would be losing a real measurement to a packaging decision.

Run it:

    python scripts/gen_readme.py --check     # what CI runs; nonzero if the README has drifted
    python scripts/gen_readme.py --write     # regenerate the blocks in place
    python scripts/gen_readme.py --list      # the block names and their sizes

**What this script needs installed.** The base install plus the ``[verifier]`` extra, which is pure
Python and pulls nothing compiled. That is the same environment ``.github/workflows/docs.yml``
already builds, and it is deliberately not the full test environment: a generator that needs torch
to render a README would be a generator nobody runs.

**Determinism.** The captured commands are run with a fixed ``COLUMNS`` so Rich wraps identically
everywhere, with ``PYTHONHASHSEED`` fixed, and from the repository root so the relative paths that
appear in their output are stable. Every iteration over a set is sorted.
"""

from __future__ import annotations

