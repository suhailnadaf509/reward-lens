#: The record is the twelve-step GRPO fixture that ships in the repository, written by a real
#: `GRPOTrainer` against real weights. A stranger cannot run the command against it without cloning
#: the repo, which is why the block below prints the invocation with a placeholder path and then
#: shows the output of the real one. The two are the same command; only the argument differs.
CAPABILITIES_ARGV = [
    "reward-lens",
    "capabilities",
    "--record",
    "tests/fixtures/grpo_run/short",
    "--grader",
    "https://my-judge.example/score",
    "--substrate",
    "NEURAL_GEN",
]

#: How many rows of each list to print before eliding. The report itself lists every one; the front
#: page shows enough to make the shape obvious and then says how many it left out, counted rather
#: than guessed. Elision is the only editorial act this file performs on captured output, and it is
#: always accompanied by the count it elided.
CAPABILITIES_AVAILABLE_SHOWN = 2
CAPABILITIES_REFUSALS_SHOWN = 2


def _split_capability_sections(text: str) -> dict[str, list[str]]:
    """Split the report into its four section headings, keeping the order they were printed in."""
    sections: dict[str, list[str]] = {}
    current = ""
    for line in text.splitlines():
        if line and not line.startswith(" "):
            current = line.split("  ")[0].strip()
            sections[current] = [line]
        elif current:
            sections[current].append(line)
    return sections


def block_capabilities() -> str:
    """The first command anyone runs, captured against the record that ships in the repository.

    The report is long by design: it lists every quantity it cannot reach and why. The front page
    shows the four resolutions in full and the first two refusals, because the point a reader needs
    in one screen is the *shape* of a refusal, not the census.
    """
    out = capture([console_script("reward-lens"), *CAPABILITIES_ARGV[1:]])
    sections = _split_capability_sections(out)
    for name in ("ACCESS RESOLVED", "REGIME MEASURED", "AVAILABLE NOW", "REFUSED, WITH REMEDY"):
        if name not in sections:
            raise SourceDrift(
                f"`reward-lens capabilities` printed no {name!r} section. The report has four "
                f"sections and the README quotes all four."
            )

    lines: list[str] = ["$ " + " ".join(CAPABILITIES_ARGV), ""]
    for name in ("ACCESS RESOLVED", "REGIME MEASURED"):
        lines.extend(ln.rstrip() for ln in sections[name] if ln.strip())
        lines.append("")

    lines.extend(_elide(sections["AVAILABLE NOW"], CAPABILITIES_AVAILABLE_SHOWN, "more available"))
    lines.append("")
    lines.extend(
        _elide(
            sections["REFUSED, WITH REMEDY"],
            CAPABILITIES_REFUSALS_SHOWN,
            "more refused, each with its own reason and its own remedy",
        )
    )
    return fence("\n".join(lines).rstrip())


#: A row in the availability or refusal list starts at column two with a quantity id. Continuation
#: lines are indented further, so the head of each entry is what this matches.
_REPORT_ROW_RE = re.compile(r"^  \S")


def _elide(section: list[str], keep: int, what: str) -> list[str]:
    """Keep the heading and the first ``keep`` entries, then say how many were dropped."""
    heads = [i for i, ln in enumerate(section[1:], start=1) if _REPORT_ROW_RE.match(ln)]
    if not heads:
        # Both lists have an empty form, "nothing. No registered estimator resolves ...", and that
        # is a real answer rather than a missing section, so it is printed as it stands.
        return [ln.rstrip() for ln in section if ln.strip()]
    end = heads[keep] if len(heads) > keep else len(section)
    out = [ln.rstrip() for ln in section[:end] if ln.strip()]
    dropped = len(heads) - min(keep, len(heads))
    if dropped:
        out.append(f"  ... {dropped} {what}")
    return out


