#: The exact source the README shows and the exact source this script runs. There is one copy of
#: it, here, so the two cannot come apart. It writes the grader it is about to measure, because a
#: front-page example that points at a file the reader does not have is not runnable, and the whole
#: claim of this file is that everything on the page ran.
CARD_PLAN_SOURCE = """\
from pathlib import Path

from reward_lens.measure.card import CardInputs, card_plan
from reward_lens.verifier import ListCorpus, Rollout, VerifierUnderTest

# Your grader. This one is four lines; SWE-bench's is four hundred.
Path("grade.py").write_text(
    "def grade(answer, gold):\\n"
    "    return 1.0 if answer.strip() == gold.strip() else 0.0\\n"
)

plan = card_plan(
    CardInputs(
        verifier=VerifierUnderTest(Path("grade.py"), entrypoint="grade"),
        corpus=ListCorpus(
            tuple(Rollout(id=f"r{i}", inputs={"answer": "4", "gold": "4"}) for i in range(20))
        ),
    )
)
print(plan.render())
"""

#: Which of the thirteen card fields the front page shows in full. One that reads, and two that
#: refuse for different reasons, which is the whole lesson in three lines.
CARD_PLAN_FIELDS_SHOWN = ("coverage", "variance components", "curl mass")


def block_card_plan_code() -> str:
    return fence(CARD_PLAN_SOURCE.rstrip(), "python")


def _card_plan_output(tmp: Path) -> str:
    script = tmp / "card_plan_example.py"
    script.write_text(CARD_PLAN_SOURCE, encoding="utf-8")
    return capture([sys.executable, str(script)], cwd=tmp)


def block_card_plan_output(tmp: Path) -> str:
    """The plan the code above actually prints, trimmed to a few of the card's fields.

    `card_plan` makes no grader call and loads no model, so this runs in about a second and is the
    cheapest honest thing the library does.
    """
    out = _card_plan_output(tmp)
    lines = out.splitlines()
    header = [ln for ln in lines[:8] if ln.strip()]
    total = int(
        re.search(r"\d+ of (\d+) fields would read", out).group(1)  # type: ignore[union-attr]
        if re.search(r"\d+ of (\d+) fields would read", out)
        else 0
    )
    if not total:
        raise SourceDrift(
            "the card plan printed no 'N of M fields would read' summary. That line is what the "
            "README counts against, so the elision below would be guessing."
        )

    keep: list[str] = []
    capturing = False
    seen: list[str] = []
    for ln in lines:
        name = ln[2:].split("  ")[0].strip() if ln.startswith("  ") and ln[2:3] != " " else ""
        if name:
            capturing = name in CARD_PLAN_FIELDS_SHOWN
            if capturing:
                seen.append(name)
        if capturing:
            keep.append(ln)
    missing = [f for f in CARD_PLAN_FIELDS_SHOWN if f not in seen]
    if missing:
        raise SourceDrift(
            f"the card plan no longer has {missing} among its fields, and the README quotes them. "
            f"Repoint CARD_PLAN_FIELDS_SHOWN at fields the card still has."
        )
    body = "\n".join(header + [""] + keep).rstrip()
    elided = total - len(CARD_PLAN_FIELDS_SHOWN)
    return fence(body + f"\n\n  ... {elided} more fields, same shape")


# ---------------------------------------------------------------------------
# Block: the grader card, on four real scoring programs
# ---------------------------------------------------------------------------

#: Rendered grader cards, one file per scoring program. `reward_lens.measure.card` writes them, and
#: this script reads them rather than re-rendering them: a render needs the four graders' source and
#: a corpus fetched from four upstream projects, which is not something a README build should do.
#: The cards are release artifacts published beside the run, not files this tree carries, so the two
#: blocks below are optional and skip themselves when the directory is absent.
CARD_RELEASE = ROOT / "artifacts" / "grader_cards"
CARD_SUBJECTS = ("is_equiv", "swebench", "verl_gsm8k", "verl_search_r1")

_CARD_TOTALS_RE = re.compile(r"^\s*(\d+) of (\d+) fields read and (\d+) refused", re.M)


def _require_cards() -> None:
    if not CARD_RELEASE.is_dir():
        raise MissingArtifact(
            f"no rendered grader cards at {CARD_RELEASE.relative_to(ROOT)}. They are published "
            f"with the run rather than carried in the source tree."
        )


def card_totals() -> tuple[int, int, int, int]:
    """Add up the four rendered cards: subjects, fields, read, refused.

    Computed from the cards themselves rather than restated, so a card that gains a field or starts
    reading one it used to refuse moves the front page with it.
    """
    _require_cards()
    n_read = n_refused = n_fields = 0
    for subject in CARD_SUBJECTS:
        text = read(CARD_RELEASE / f"{subject}.txt")
        m = _CARD_TOTALS_RE.search(text)
        if m is None:
            raise SourceDrift(
                f"the rendered card for {subject} carries no 'N of M fields read and K refused' "
                f"line. That line is what the README counts, so either the renderer changed its "
                f"summary or the card was re-rendered by something else."
            )
        n_read += int(m.group(1))
        n_fields += int(m.group(2))
        n_refused += int(m.group(3))
    if n_read + n_refused != n_fields:
        raise SourceDrift(
            f"the four cards report {n_read} read and {n_refused} refused against {n_fields} "
            f"fields, which do not add up. One of them is being parsed wrong."
        )
    return len(CARD_SUBJECTS), n_fields, n_read, n_refused


def block_card_totals() -> str:
    """One sentence, with every number in it computed from the rendered cards."""
    n_subjects, n_fields, n_read, n_refused = card_totals()
    by_reason: dict[str, int] = {}
    for subject in CARD_SUBJECTS:
        for line in read(CARD_RELEASE / f"{subject}.txt").splitlines():
            m = re.match(r"^\s+\S.*?REFUSED\s+([A-Z_]+)\s*$", line)
            if m:
                by_reason[m.group(1)] = by_reason.get(m.group(1), 0) + 1
    order = sorted(by_reason.items(), key=lambda kv: (-kv[1], kv[0]))
    tally = ", ".join(f"{n} {name}" for name, n in order)
    return fence(
        f"{n_subjects} scoring programs, {n_fields} card fields\n"
        f"  {n_read} read\n"
        f"  {n_refused} refused, and none of them for want of access:\n"
        f"      {tally}\n"
        f"\n"
        f"  rendered by `reward_lens.measure.card` and published with the run"
    )


#: The stretch of the `is_equiv` card the README quotes. Line numbers move; this is anchored on the
#: field name, which does not.
CARD_EXCERPT_FIELDS = ("surviving mutants", "exploit-family accounting")


def block_card_excerpt() -> str:
    """Two fields from a real card: one that read and said something bad, one that refused."""
    _require_cards()
    text = read(CARD_RELEASE / "is_equiv.txt")
    lines = text.splitlines()
    starts = {}
    for i, ln in enumerate(lines):
        for f in CARD_EXCERPT_FIELDS:
            if ln.startswith(f"  {f} ") or ln.strip() == f:
                starts.setdefault(f, i)
    missing = [f for f in CARD_EXCERPT_FIELDS if f not in starts]
    if missing:
        raise SourceDrift(
            f"the rendered `is_equiv` card no longer has {missing}, and the README quotes them."
        )
    out: list[str] = []
    for f in CARD_EXCERPT_FIELDS:
        i = starts[f]
        j = i + 1
        while j < len(lines) and (not lines[j].strip() or lines[j].startswith(" " * 25)):
            j += 1
        out.extend(lines[i:j])
    return fence(rewrap("\n".join(out).rstrip()))


