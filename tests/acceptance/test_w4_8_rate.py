def test_ad_runs_on_the_real_grpo_record_and_the_worst_step_is_the_last_one():
    """A real optimisation trace: real advantages, a real learning-rate schedule, real abstentions.

    The schedule decays linearly to zero, so its log derivative is small at every step and unbounded
    at the last one. That is the case a window maximum hides and per-step `Ad` shows, and it is not
    a contrived example: it is what the shipped schedule of a real trainer does.
    """
    run = open_fixture("long") if (FIXTURES / "long" / "runs").is_dir() else open_fixture("short")
    reading = adiabaticity(run, floors=FAST_TAU)
    if isinstance(reading, Refusal):
        # A bounded refusal is a correct answer here and the bound is the reading.
        assert reading.reason is RefusalReason.ABOVE_LOD_BELOW_LOQ
        assert reading.is_bounded
        return

    n_steps = len(run.steps.indices)
    assert len(reading.per_step) == n_steps - 1
    assert reading.parameter == "learning_rate"
    assert reading.worst_step == max(run.steps.indices)
    assert reading.per_step[-1].rate == pytest.approx(math.log(2.0), rel=1e-6), (
        "a schedule decaying linearly to zero halves on its final step, so d log lambda / dt is "
        "exactly ln 2 there"
    )
    assert reading.median_ad < reading.ad
    assert reading.tau.tau >= 0.0


def test_the_real_record_is_a_run_where_w2_7_declines_and_this_package_answers():
    """The second clause, on the real subject rather than on a synthetic one.

    The 200-step GRPO record's early group-mean series has an uncorrected lag-1 coefficient of
    -0.030, so `rate/regime.py` reports no relaxation time and `QUASI_STATIC` comes back `None`
    while the learning rate is halving on the final step. The corrected coefficient is +0.013 and
    its interval reaches 0.85 steps, which puts the upper end of `Ad` at 0.59 against a threshold of
    1, so the condition is answered and the answer is that the run is quasi-static.
    """
    if not (FIXTURES / "long" / "runs").is_dir():
        pytest.skip("this assertion is about the 200-step record specifically")
    run = open_fixture("long")

    alone = measure_regime(run).conditions[RegimeCondition.QUASI_STATIC]
    assert alone.holds is None
    assert "tau_relax is not available" in alone.detail

    reading = adiabaticity(run, floors=FAST_TAU)
    assert not isinstance(reading, Refusal)
    assert reading.holds is True
    assert reading.ad_high < reading.threshold

    answered = measure_regime(run, inputs=regime_inputs(reading)).conditions[
        RegimeCondition.QUASI_STATIC
    ]
    assert answered.holds is True
    assert answered.statistic == pytest.approx(reading.ad_high)

    # And the disagreement between the two rung-0 estimators, which on this run is the whole of
    # this package's estimate because the cheap one declined.
    transfer = tau_transfer(reading)
    assert transfer.value == pytest.approx(reading.tau.tau)
    assert "an absence rather than a zero" in transfer.method


def test_h4_refuses_on_every_channel_the_real_record_carries():
    """There is no behavioural transition in this run, so every channel has to refuse.

    Reporting a width here would be the confident wrong number this library exists to prevent: the
    logistic would fit something, the number would look like a transition width, and every lead
    scored against it would inherit the false precision. Two constant channels refuse as
    `RECORD_INCOMPLETE` and the rest as `BELOW_LOD` with the information criterion in the refusal.
    """
    run = open_fixture("long") if (FIXTURES / "long" / "runs").is_dir() else open_fixture("short")
    have = available_series(run)
    assert have, "the record carries no per-step numeric channel at all"

    verdicts: dict[str, str] = {}
    for name in ("group_mean", "reward", "reward_std", "grad_norm", "entropy"):
        if name not in have:
            continue
        values, indices = series_from_run(run, name)
        out = fit_transition(values, indices, series=name, criteria=FAST_FIT)
        assert isinstance(out, Refusal), (
            f"a transition width was reported for {name!r} on a run with no transition in it"
        )
        verdicts[name] = out.reason.name
    assert verdicts, "no channel was tested"
    assert set(verdicts.values()) <= {"BELOW_LOD", "RECORD_INCOMPLETE"}


def test_the_instrument_emits_or_refuses_on_the_real_record_and_never_raises():
    """Both instruments, through `estimate`, on a real record. Evidence or a Refusal, never both."""
    run = open_fixture("long") if (FIXTURES / "long" / "runs").is_dir() else open_fixture("short")
    for instrument in (
        Adiabaticity(run, floors=FAST_TAU),
        TransitionWidth(run, series="group_mean", criteria=FAST_FIT),
    ):
        reading = instrument.estimate(_context())
        if isinstance(reading, Refusal):
            assert reading.remedy.strip()
            assert reading.reason in RefusalReason
        else:
            assert reading.quantity in ("run.adiabaticity", "run.transition_width")
