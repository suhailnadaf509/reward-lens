def test_p9_resolves_against_its_own_registered_rule_and_says_so(closures):
    """P9, resolved on both runs. The registered rule fails and the flattering reading is declined.

    Registered: "`Var(rho)` accounted for by `sum u_i^2` within its stated interval, or an
    unmodelled term is named." Across the two runs the worst feature is `response_chars` on
    `short/` at ratio 0.555 [0.187, 0.921], which does not contain 1, so the registered indicator
    is 0 and **P9 resolves against the prediction**.

    The flattering reading is available and is declined here: the 200-step run closes on all three
    features, and reporting that alone would be reporting the better of two runs. The second reason
    to decline is stronger and is the one that would apply even if both had closed: the detection
    floor is 854,000 times the prediction being arbitrated, so neither verdict could have failed at
    the scale that matters.
    """
    resolution = score_closure([verdict for verdict, _, _ in closures.values()])
    assert resolution.resolved
    assert resolution.n_runs == 2
    assert resolution.n_closed == 1
    assert resolution.metrics()[METRIC_INTERVAL_CONTAINS_ONE] == 0.0
    assert not resolution.interval_contains_one
    assert resolution.worst_feature == "response_chars"
    assert resolution.n_missing == 4
    assert resolution.power_ratio > 1e5
    assert "not preregistered" in resolution.render()


def test_p9_does_not_fire_its_kill_criterion(closures):
    """The catalogue's kill for F4 is that the budget closes on no run. It closes on one."""
    resolution = score_closure([verdict for verdict, _, _ in closures.values()])
    kill = BUDGET_CLOSURE_SPEC.kill_criteria[0]
    assert kill.comparator == "<" and kill.threshold == 1.0
    assert resolution.metrics()[kill.metric] >= kill.threshold


def test_p10_resolves_against_its_registered_rule_and_is_reported_unresolved(runs):
    """P10, on the only record long enough to regress across. Both the number and the defect.

    Registered: "OLS slope of `Delta z` on `eta G beta` across a window, interval excluding zero",
    against a permuted null. Measured: slope -66825 [-246789, 113323] over 199 step pairs, uncentred
    `R²` 0.0017, permuted-step null `p = 0.21`. **The interval contains zero and the null is not
    beaten, so P10 resolves against the prediction as registered.**

    And the honest number rather than the registered one: `G` is the covariance bound, so
    `eta*G*beta` reduces to `eta*S` exactly and this fit is F2's `eta_eff` rescaled. It is not a
    test of Lande's equation whichever way the interval falls, so the resolution is reported
    **unresolved** rather than claimed as a refutation. A refutation of Lande's equation is a
    result worth having and this analysis cannot supply one.
    """
    samples, _, _, steps, _ = _books(runs["long"])
    scales = feature_scales(samples)
    fit = fit_lande(steps, scales)
    draws = permuted_lande_null(steps, scales, n_draws=1000)
    resolution = score_lande(fit, draws)

    assert not resolution.excludes_zero
    assert resolution.ci_low < 0.0 < resolution.ci_high
    assert resolution.null_p > 0.05
    assert resolution.r_squared < 1e-2

    assert resolution.is_degenerate
    assert resolution.metrics()[METRIC_LANDE_DEGENERATE] == 1.0
    assert not resolution.resolved
    assert "rung-2 Fisher solve" in resolution.render()


def test_p10_fires_its_kill_criterion_on_this_subject(runs):
    """`R²` below 1e-3 means the slope is a line through a cloud, and the kill says to report it."""
    samples, _, _, steps, _ = _books(runs["long"])
    fit = fit_lande(steps, feature_scales(samples))
    resolution = score_lande(fit, permuted_lande_null(steps, feature_scales(samples), n_draws=200))
    kill = LANDE_SLOPE_SPEC.kill_criteria[0]
    assert resolution.metrics()[kill.metric] < 1e-2
