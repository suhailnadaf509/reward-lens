def test_the_closure_test_runs_on_two_real_runs(closures):
    """The clause's first half: two real runs, both reconciled, both reaching a verdict."""
    assert set(closures) == {"short", "long"}
    for name, (verdict, steps, budgets) in closures.items():
        assert steps, f"{name} produced no reconciled step pair"
        assert budgets, f"{name} produced no feature budget"
        assert verdict.verdict != "undetermined", f"{name} reached no verdict"
        assert verdict.n_features == 3, f"{name} should reconcile the three varying features"


def test_the_verdict_is_published_either_way(closures):
    """The clause's second half. The two runs disagree, and both verdicts are carried on the reading.

    `long/` closes and `short/` comes back `over`. Asserting the pair rather than one of them is
    what makes this a test of publication rather than of a hoped-for outcome: a run whose budget
    does not close still produces a verdict, a ratio, an interval and a named dominant term.
    """
    long_verdict, _, _ = closures["long"]
    short_verdict, _, _ = closures["short"]
    assert long_verdict.verdict == "closed"
    assert short_verdict.verdict == "over"
    for verdict in (long_verdict, short_verdict):
        for feature in verdict.features:
            assert np.isfinite(feature.ratio)
            assert np.isfinite(feature.ci_low) and np.isfinite(feature.ci_high)
            assert feature.dominant != "none"
            assert feature.verdict in {"closed", "over", "incomplete", "unmodelled"}
        assert verdict.render()


def test_the_long_run_closes_on_every_feature(closures):
    """The published numbers: three intervals on `Var(ρ)/Σu²`, every one containing 1."""
    verdict, _, _ = closures["long"]
    assert verdict.n_steps == 199
    for feature in verdict.features:
        assert feature.ci_low <= 1.0 <= feature.ci_high, feature.render()
        assert feature.verdict == "closed"
    ratios = {f.feature: f.ratio for f in verdict.features}
    assert ratios["response_chars"] == pytest.approx(1.082, abs=0.02)


def test_the_short_run_does_not_close_and_says_which_way(closures):
    """`over` is a defect in the budget, and it is reported rather than clipped to `closed`."""
    verdict, _, _ = closures["short"]
    assert verdict.n_steps == 11
    worst = verdict.features[0]
    assert worst.feature == "response_chars"
    assert worst.verdict == "over"
    assert worst.ci_high < 1.0
    # The remedy names the two mechanisms that produce `over` on a short window rather than
    # leaving the reader to find them: an inflated `u_MC` and the negative autocorrelation that
    # overlapping step pairs put into the residual.
    assert "defect in the budget" in worst.detail
    assert "u_MC" in worst.detail and "autocorrelated" in worst.detail
    assert "Widen the window" in worst.detail


