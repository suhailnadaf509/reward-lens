def test_g_equal_to_c_reproduces_the_ledger_residual_exactly(runs):
    """`Gβ = C·C⁻¹S = S`, so F4's residual is F1's. The reduction is the join's own self-check.

    This is why the rung-0 reading is degenerate and it is asserted rather than argued: at the
    covariance bound the reconciliation adds nothing to the Price ledger, and any claim that it
    does on this record would be a claim about float noise.
    """
    for name, run in runs.items():
        _, _, _, steps, _ = _books(run)
        worst = max(abs(row.residual - row.ledger_residual) for step in steps for row in step.rows)
        scale = max(abs(row.delta_z_obs) for step in steps for row in step.rows)
        assert worst < 1e-12 * max(scale, 1.0), f"{name}: {worst}"


def test_a_mismatched_feature_basis_refuses_rather_than_aligning_by_name(runs):
    """D19's join key, enforced. A reordered basis is a different vector space."""
    from dataclasses import replace as _replace

    run = runs["long"]
    samples, ledgers, g, _, _ = _books(run)
    scrambled = _replace(g, names=tuple(reversed(g.names)))
    instrument = ReconciliationResidual(run, SurfaceFeatures(), scrambled)
    reading = instrument.estimate(_ctx())
    assert isinstance(reading, Refusal)
    assert reading.reason is RefusalReason.UNIT_MISMATCH
    assert "one `TrajectoryFeaturiser`" in reading.remedy


