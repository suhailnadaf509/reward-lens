def _open(which: str):
    root = FIXTURES / which
    if not root.exists() or not (root / "runs").exists():
        return None
    try:
        run_id = next(p.name for p in (root / "runs").iterdir())
    except StopIteration:
        return None
    try:
        return open_run(root, run_id.replace("run_", "run:"))
    except Exception:  # a fixture mid-write is absent rather than broken
        return None


def _books(run):
    """Every object the clause needs, built once from a real record."""
    samples = steps_from_run(run, SurfaceFeatures())
    ledgers = ledger_series(samples, eta_by_step=learning_rates(run))
    g = metric_g(samples, method="covariance_bound")
    assert not isinstance(g, Refusal), g.render() if isinstance(g, Refusal) else ""
    steps = reconcile_series(samples, ledgers, g)
    budgets = itemise(steps, samples, facts_from_run(run))
    return samples, ledgers, g, steps, budgets


@pytest.fixture(scope="module")
def runs():
    """Both real GRPO records. The clause names two runs, so both are required rather than one."""
    pair = {name: _open(name) for name in ("short", "long")}
    missing = [name for name, run in pair.items() if run is None]
    if missing:
        pytest.skip(f"no GRPO record on disk for {missing} under {FIXTURES}")
    return pair


@pytest.fixture(scope="module")
def closures(runs):
    out = {}
    for name, run in runs.items():
        _, _, _, steps, budgets = _books(run)
        out[name] = (closure_of(budgets, steps, run_id=run.id), steps, budgets)
    return out


def _ctx(**kwargs) -> Context:
    return Context(access=dict(ACCESS), substrate=Substrate.PROGRAM, phase=Phase.POST_RUN, **kwargs)


