"""Acceptance: F4, the reconciliation residual budgeted, and F6, the Lande slope.

**The clause.** *The budget-closure test runs on two real runs and its verdict is published either
way.*

It runs on both, and the two verdicts differ, which is the useful outcome. Everything below is
measured on the real GRPO records under `tests/fixtures/grpo_run/`: a real `GRPOTrainer`, real
weights, real sampling, real advantages, real abstentions. `Δz`, `S`, `C` and `η` come off the
record and `G` comes from `measure.efficiency.metric_g` at rung 0. Nothing here is synthetic.

**The published verdicts.**

`long/`, 200 steps, 199 step pairs: **CLOSED.** All three varying surface features have an interval
on `Var(ρ) / Σ u_i²` containing 1: `response_chars` 1.082 [0.846, 1.341], `response_words` 1.097
[0.887, 1.302], `mean_word_length` 1.042 [0.769, 1.315], at 95% over a cluster bootstrap on step
pairs. Welch-Satterthwaite gives 2,786 effective degrees of freedom, so the coverage factor stays
at the conventional 2.

`short/`, 12 steps, 11 step pairs: **OVER.** On `response_chars` the ratio is 0.555 [0.187, 0.921],
so the budget composes to more scatter than the residual has. That is a defect in the budget rather
than a property of the run, and the two mechanisms behind it are named in
`measure.reconcile.residual`: `u_MC` is a root-mean-square over steps of a per-step standard error
estimated from eight rollouts, and the root-mean-square of a noisy quantity overstates it; and
consecutive step pairs share a step, which makes `ρ` negatively autocorrelated and biases the
sample variance across 11 overlapping pairs downward by around 18%.

**What the closure means and does not, which is the number that matters here.** `u_MC` carries
100.0% of the composed variance on every feature of both runs. The budget closing therefore says
that the movement of these features is accounted for by the sampling noise of two batches of eight
rollouts, and it is not the four books reconciling. The test's own detection floor makes this
precise: on `long/` it separates an extra term only above 3.76 in units of `response_chars`, and
the first-order prediction `η·G·β` it is arbitrating is 5.65e-06. The floor is **854,000 times**
the prediction. So the verdict `closed` is real, reproducible and could not have come out any other
way at the scale being tested, and `FeatureClosure.detectable_u` is on the reading so that no
reader has to work that out for themselves.

**Four of the nine terms are not computed on either record, and each is named.** `u_entropy` (no
trainer config in the record carries an entropy coefficient, and `optimizer.entropy` is the
measured entropy rather than the coefficient), `u_momentum` (`grad_norm_unclipped` and
`update_norm` are both `None`, and the recorded optimiser is `adamw_torch_fused`, so this term is
certainly non-zero and certainly not measurable here), `u_curv` (no record carries a second
derivative), and `u_clip` (`clip_fraction` is `None`). Two of the five that are computed are
exactly zero for stated reasons rather than for want of a number: `beta` is 0.0 in the schedule at
every step of both runs, so there is no KL pull, and every trajectory segment declares
`staleness_steps = 0`, so every rollout was generated by the policy that was then updated on it.

**F6 and the rung-2 attempt, recorded here so a skipped run still carries the result.** At rung 0
`G = C`, so `ηGβ = ηS` exactly and the Lande fit is F2's `η_eff` rescaled. To get a `G` that is not
`C` the rung-2 Fisher solve was run on a 24-step window of `long/`, loading the same
`trl-internal-testing/tiny-Qwen3ForCausalLM` the record names, 192 rollouts and 2,453,368
parameters, through `measure.efficiency.scores.sequence_scores` and
`metric_g(method="fisher_kernel")`. It ran, and the result is a finding about the estimator rather
than about the run: `h² = G_ii/C_ii` came out **0.99135 to 0.99143 on all three features against a
damping of 0.0087442**, which is the same number. The empirical Fisher has rank at most the rollout
count, so with 192 rollouts against 2.45M parameters every feature lies exactly in the span of the
score vectors, `N = C − G` collapses onto the regulariser, and the reported heritability is `1 − λ`
rather than a property of the policy. `_is_degenerate` catches that case as well as the exact one,
which is why P10 is reported unresolved at both rungs. The slope there was -37624 [-279973,
232981] over 23 step pairs at `R²` 0.0018 with a permuted-step null at `p = 0.62`.

**Is two runs enough for what closure needs?** For the mechanics, yes, and the two disagreeing is
worth more than two agreeing. For a characterisation of the instrument, no, and the number is
this: with four of nine terms unmeasured the composed uncertainty is a lower bound, so neither
verdict can distinguish an unmodelled term from an unmeasured one. Closing that needs a record
carrying `clip_fraction`, `grad_norm_unclipped` and `update_norm`, which is a change to the tap and
not to this instrument, and one Hessian-vector product per step at `POLICY: BACKWARD`.
"""

