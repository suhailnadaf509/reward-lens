def test_f4_downgrades_outside_linear_response_rather_than_refusing(runs):
    """Outside the envelope the residual is still the thing worth reading, so it is not refused.

    The instrument that can say "the first order explains nothing here" has to be able to run where
    the first order explains nothing. The regime `downgrade` behaviour is what says so: the
    quantity stays defined and its trust is capped.
    """
    from reward_lens.measure.rate.regime import RegimeInputs, measure_regime

    _, _, g, _, _ = _books(runs["long"])
    instrument = BudgetClosure(runs["long"], SurfaceFeatures(), g)
    assert instrument.envelope.on_violation == "downgrade"
    assert RegimeCondition.LINEAR_RESPONSE in instrument.envelope.requires

    # The measured Lambda on this record is 0.0012, well under the 0.5 floor, so LINEAR_RESPONSE
    # really is violated here rather than being violated by an argument passed to make it so.
    regime = measure_regime(
        runs["long"], window=(0, 60), inputs=RegimeInputs(explained_fraction=0.0012)
    )
    assert any(
        v.condition is RegimeCondition.LINEAR_RESPONSE
        for v in instrument.envelope.violations(regime)
    )
    pre = instrument.preflight(_ctx(regime_reading=regime))
    assert pre.ok, "outside LINEAR_RESPONSE the residual is downgraded rather than refused"
    assert pre.trust_cap is not None
    reading = instrument.estimate(_ctx(regime_reading=regime))
    assert isinstance(reading, Evidence)


def test_f6_does_not_require_the_condition_that_is_nearly_its_own_question(runs):
    """`Λ` is the `R²` of `Δz` on `η·S`; the Lande slope is the slope of `Δz` on `η·G·β`."""
    _, _, g, _, _ = _books(runs["long"])
    envelope = LandeSlope(runs["long"], SurfaceFeatures(), g).envelope
    assert RegimeCondition.LINEAR_RESPONSE not in envelope.requires
    assert envelope.requires == frozenset(
        {RegimeCondition.GROUP_NONDEGENERATE, RegimeCondition.NEAR_POLICY}
    )


