def test_a_closed_budget_reports_the_floor_it_could_not_have_failed_below(closures):
    """`u_MC` carries the whole budget, so the test cannot see a term the size of the prediction.

    This is the number that stops "the budget closes" being read as "the four books reconcile". On
    the 200-step record the closure test separates an extra term only above 3.76 in units of
    `response_chars`, and the first-order prediction it arbitrates is 5.65e-06.
    """
    verdict, _, _ = closures["long"]
    chars = verdict.features[0]
    assert chars.feature == "response_chars"
    assert chars.verdict == "closed"
    assert not chars.powered_at_prediction
    assert chars.detectable_u > 1e5 * chars.predicted_rms
    assert "could not have failed" in chars.render()


def test_the_dominant_term_is_monte_carlo_on_every_feature_of_both_runs(closures):
    """The GUM's payload is the last line of the table, and here it names the same term throughout."""
    for _, (verdict, _, budgets) in closures.items():
        for feature in verdict.features:
            assert feature.dominant == "u_MC"
        for budget in budgets:
            shares = budget.budget.shares()
            assert shares["u_MC"] == pytest.approx(1.0, abs=1e-3)


